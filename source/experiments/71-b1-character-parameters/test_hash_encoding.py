"""Production-retained hash goldens; synthetic format cases are separate."""
import hashlib
import json
from pathlib import Path
import tomllib
import unittest
from hash_encoding import mesh_array_bytes, mesh_array_sha256, promoted_f32_token

EXP = Path(__file__).resolve().parent


class ProductionHashEncoding(unittest.TestCase):
    def test_all_eight_actual_production_array_hashes_match_retained_buffers(self):
        fixture = json.loads((EXP/'inputs/production-hash-golden.json').read_text())
        self.assertEqual(fixture['source_capture_sha256'], '9cde54133d6b24eca8dfa155105c5c9ae7c9d2085e769d5978c22e8cfc184ef6')
        self.assertEqual(fixture['source_request_id'], 'n68-combined-textured')
        self.assertEqual(fixture['source_freeze68r2_sha256'], 'e6a77816b11788c449039883ef0f12efc6d2ed59b31692d5d16094027363fe67')
        self.assertEqual({r['role'] for r in fixture['records']}, {'eyes','hair'})
        for record in fixture['records']:
            self.assertEqual(len(record['arrays']['positions']), {'eyes':96,'hair':991}[record['role']])
            for key, digest in [('positions','positions_sha256'),('normals','normals_sha256'),('uv_0','uv_sha256'),('indices','indices_sha256')]:
                # Expected hashes are the retained production appearance_snapshot values,
                # not regenerated by this Python encoder or synthetic schema fixture.
                with self.subTest(role=record['role'], array=key):
                    self.assertEqual(mesh_array_sha256(record['arrays'][key], integer=key=='indices'), record['production_hashes'][digest])
        # Python's default JSON notation is observably not the producer encoding.
        eye = next(r for r in fixture['records'] if r['role']=='eyes')
        naive = json.dumps(eye['arrays']['normals'], separators=(',',':')).encode()
        self.assertNotEqual(hashlib.sha256(naive).hexdigest(), eye['production_hashes']['normals_sha256'])

    def test_locked_producer_versions_and_features_match_encoder_contract(self):
        packages = tomllib.loads((EXP/'Cargo.lock').read_text())['package']
        self.assertEqual([p['version'] for p in packages if p['name']=='serde_json'], ['1.0.152'])
        self.assertEqual([p['version'] for p in packages if p['name']=='zmij'], ['1.0.23'])
        self.assertNotIn('arbitrary_precision', (EXP/'Cargo.toml').read_text())

    def test_f32_promotion_fixed_exponent_boundaries_negative_zero_and_indices(self):
        for value, expected in [(0.,'0.0'),(-0.,'-0.0'),(1.,'1.0'),
            (2.**-16,'0.0000152587890625'),(2.**-17,'7.62939453125e-6'),
            (-2.**-17,'-7.62939453125e-6'),(2.**50,'1125899906842624.0'),
            (2.**54,'1.8014398509481984e+16'),(2.**64,'1.8446744073709552e+19')]:
            with self.subTest(value=value):self.assertEqual(promoted_f32_token(value),expected)
        self.assertEqual(mesh_array_bytes([[1.,-0.],[2.**-17,2.**-16]]), b'[[1.0,-0.0],[7.62939453125e-6,0.0000152587890625]]')
        self.assertEqual(mesh_array_bytes([0,1,2,4294967295], integer=True), b'[0,1,2,4294967295]')
        self.assertNotEqual(mesh_array_sha256([0,1,2], integer=True),mesh_array_sha256([2,1,0], integer=True))

    def test_nonfinite_non_f32_and_malformed_index_values_reject(self):
        for value in [float('nan'),float('inf'),float('-inf'),0.1,1e100,True,None,'0']:
            with self.subTest(value=value),self.assertRaises(ValueError):mesh_array_bytes([[value]])
        for value in [-1,4294967296,0.,True,None]:
            with self.subTest(index=value),self.assertRaises(ValueError):mesh_array_bytes([value], integer=True)


if __name__=='__main__':unittest.main()
